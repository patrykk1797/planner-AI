/**
 * Fast authoritative spec lookup for popular running shoe queries.
 * Preserves user's exact generation numbers (e.g. Kayano 32, Novablast 5, Pegasus 42)
 * and never downgrades to older versions from catalog.
 */
export function lookupKnownShoeSpecs(query: string): KnownShoeSpec | null {
  if (!query) return null;
  const q = query.toLowerCase().trim();

  // Extract trailing or embedded generation number from query (e.g. "32", "5", "42")
  const queryGenMatch = q.match(/\b(\d{1,2})\b/);
  const queryGen = queryGenMatch ? queryGenMatch[1] : null;

  // 1. First priority: match shoes that specifically match the generation number if present
  if (queryGen) {
    for (const shoe of KNOWN_FLAGSHIP_SHOES) {
      if (shoe.keywords.some((k) => k.includes(queryGen) && (q.includes(k) || k.includes(q)))) {
        return shoe;
      }
    }
  }

  // 2. Exact or partial keyword match
  for (const shoe of KNOWN_FLAGSHIP_SHOES) {
    if (shoe.keywords.some((k) => q.includes(k) || k.includes(q))) {
      // If query specified a different generation number, preserve user's generation
      if (queryGen) {
        const shoeGenMatch = shoe.canonicalName.match(/\b(\d{1,2})\b/);
        if (shoeGenMatch && shoeGenMatch[1] !== queryGen) {
          return {
            ...shoe,
            canonicalName: shoe.canonicalName.replace(/\b\d{1,2}\b/, queryGen),
          };
        }
      }
      return shoe;
    }
  }

  // 3. Token overlap match
  const queryTokens = q.split(/[\s\-_\/]+/).filter((t) => t.length > 2);
  let bestMatch: KnownShoeSpec | null = null;
  let maxScore = 0;

  for (const shoe of KNOWN_FLAGSHIP_SHOES) {
    let score = 0;
    const shoeText = `${shoe.canonicalName} ${shoe.brand} ${shoe.keywords.join(' ')}`.toLowerCase();
    for (const token of queryTokens) {
      if (shoeText.includes(token)) score++;
    }
    if (score > maxScore && score >= 2) {
      maxScore = score;
      bestMatch = shoe;
    }
  }

  if (bestMatch && queryGen) {
    const shoeGenMatch = bestMatch.canonicalName.match(/\b(\d{1,2})\b/);
    if (shoeGenMatch && shoeGenMatch[1] !== queryGen) {
      return {
        ...bestMatch,
        canonicalName: bestMatch.canonicalName.replace(/\b\d{1,2}\b/, queryGen),
      };
    }
  }

  return bestMatch;
}
